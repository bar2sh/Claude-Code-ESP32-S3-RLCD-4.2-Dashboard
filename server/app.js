async function onAddSubmit(e) {
  e.preventDefault();
  const err = $('add-error');
  err.textContent = '';
  const token = $('add-token').value.trim();
  if (!token) {
    err.textContent = ui(t('add.empty'));
    $('add-token').focus();
    return;
  }
  if (!/^[\x21-\x7e]+$/.test(token)) {
    err.textContent = ui(t('add.badChars'));
    return;
  }
  await withBusy($('add-submit'), async () => {
    // a separate client: a wrong new token must not invalidate the active profile
    const probe = createApi({ token, onConnection: setOnline });
    try {
      const name = await probe.me();
      const p = addProfile(name, token);
      if (activate(p.id)) toast(t('add.added', { name }));
    } catch (ex) {
      err.textContent = errorMessage(ex);
    }
  }, t('busy.checking'));
}

