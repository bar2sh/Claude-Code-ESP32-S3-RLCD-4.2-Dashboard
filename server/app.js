// ---------- Wallpaper ----------

function showNoWallpaper(text = t('wall.none')) {
  $('wall-current').hidden = true;
  const note = $('wall-none');
  note.textContent = text;
  note.hidden = false;
}

function paint(canvas, bytes) {
  canvas.getContext('2d').putImageData(new ImageData(wallpaperToRgba(bytes), W, H), 0, 0);
}

function drawCurrent(bytes) {
  paint($('wall-current'), bytes);
  $('wall-current').hidden = false;
  $('wall-none').hidden = true;
}

/** GET wallpaper when wallpaper_rev changed; 0 means none, so no request. */
async function loadWallpaper() {
  const api = S.api;
  if (!api) return;
  if (!S.state) {
    if (S.wallRev === null) showNoWallpaper(loadingText());
    return;
  }
  const rev = Number(S.state.wallpaper_rev) || 0;
  if (rev === S.wallRev) return;
  if (!rev) {
    S.wallRev = 0;
    showNoWallpaper();
    return;
  }
  if (S.wallLoading) {
    S.wallAgain = true;
    return;
  }
  S.wallLoading = true;
  const err = $('wall-current-error');
  try {
    const bytes = await api.getWallpaper();
    if (api !== S.api) return;
    if (bytes && bytes.length !== BYTES) throw new ApiError(t('wall.badSize', { n: BYTES }));
    if (bytes) drawCurrent(bytes);
    else showNoWallpaper();
    S.wallRev = rev;
    err.textContent = '';
  } catch (ex) {
    if (api === S.api && !quiet(ex)) err.textContent = errorMessage(ex);
  } finally {
    S.wallLoading = false;
    if (S.wallAgain) {
      S.wallAgain = false;
      loadWallpaper();
    }
  }
}

/**
 * The picked image as RGBA pixels. EXIF orientation is applied by the browser. The image is first scaled
 * to at most twice the size the screen needs, so dither.js averages a few pixels instead of millions.
 */
async function decodeImage(file) {
  let source = null;
  let width = 0;
  let height = 0;
  let url = '';
  try {
    if (typeof createImageBitmap === 'function') {
      try {
        source = await createImageBitmap(file, { imageOrientation: 'from-image' });
        ({ width, height } = source);
      } catch {
        source = null; // older Safari takes no options here; <img> below tries again
      }
    }
    if (!source) {
      url = URL.createObjectURL(file);
      source = await new Promise((resolve, reject) => {
        const img = new Image();
        img.onload = () => resolve(img);
        img.onerror = () => reject(new Error('image'));
        img.src = url;
      });
      width = source.naturalWidth;
      height = source.naturalHeight;
    }
    if (!(width > 0 && height > 0)) throw new Error('image');
    const k = Math.min(1, 2 * Math.max(W / width, H / height));
    const cw = Math.max(1, Math.round(width * k));
    const ch = Math.max(1, Math.round(height * k));
    const canvas = document.createElement('canvas');
    canvas.width = cw;
    canvas.height = ch;
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = 'high';
    ctx.drawImage(source, 0, 0, cw, ch); // transparent pixels stay transparent; dither.js puts them on white
    return { width: cw, height: ch, data: ctx.getImageData(0, 0, cw, ch).data };
  } finally {
    if (source && typeof source.close === 'function') source.close();
    if (url) URL.revokeObjectURL(url);
  }
}

