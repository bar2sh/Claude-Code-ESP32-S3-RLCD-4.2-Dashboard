/** Blocks a button for the length of its request. aria-disabled instead of disabled keeps the focus on it. */
async function withBusy(btn, fn, label) {
  if (busy.has(btn) || btn.disabled) return;
  busy.add(btn);
  const old = btn.textContent;
  btn.setAttribute('aria-disabled', 'true');
  btn.setAttribute('aria-busy', 'true');
  if (label) btn.textContent = label;
  try {
    await fn();
  } finally {
    busy.delete(btn);
    btn.removeAttribute('aria-disabled');
    btn.removeAttribute('aria-busy');
    if (label) btn.textContent = old;
  }
}

let toastSeq = 0;

/** A success note that disappears after 4 s. Cleared first, so the same text is announced again. */
function toast(text) {
  const seq = ++toastSeq;
  const el = $('toast');
  el.textContent = '';
  requestAnimationFrame(() => {
    if (seq !== toastSeq) return;
    el.textContent = ui(text);
    el.classList.add('show');
    setTimeout(() => {
      if (seq !== toastSeq) return;
      el.classList.remove('show');
      setTimeout(() => {
        if (seq === toastSeq) el.textContent = '';
      }, 300);
    }, TOAST_MS);
  });
}

const isOpen = (d) => d.hasAttribute('open');

function openDialog(d) {
  if (isOpen(d)) return;
  if (typeof d.showModal === 'function') d.showModal();
  else d.setAttribute('open', '');
}

function closeDialog(d) {
  if (!isOpen(d)) return;
  if (typeof d.close === 'function') d.close();
  else d.removeAttribute('open');
}

/** Resolves to true on the confirming button, false on "Cancel" or Esc. */
function confirmDialog(text, yesLabel = t('action.delete')) {
  const d = $('confirm');
  if (typeof d.showModal !== 'function') return Promise.resolve(window.confirm(text));
  const yes = $('confirm-yes');
  const no = $('confirm-no');
  $('confirm-text').textContent = ui(text);
  yes.textContent = yesLabel;
  return new Promise((resolve) => {
    const finish = (value) => {
      yes.removeEventListener('click', onYes);
      no.removeEventListener('click', onNo);
      d.removeEventListener('cancel', onCancel);
      closeDialog(d);
      resolve(value);
    };
    const onYes = () => finish(true);
    const onNo = () => finish(false);
    const onCancel = (e) => {
      e.preventDefault();
      finish(false);
    };
    yes.addEventListener('click', onYes);
    no.addEventListener('click', onNo);
    d.addEventListener('cancel', onCancel);
    openDialog(d);
  });
}

// ---------- profiles ----------

function loadProfiles() {
  let data = null;
  try {
    data = JSON.parse(localStorage.getItem(STORE_KEY) || 'null');
  } catch {
    data = null; // storage blocked or a broken entry: start without profiles
  }
  const profiles = [];
  const tokens = new Set();
  const ids = new Set();
  for (const p of Array.isArray(data?.profiles) ? data.profiles : []) {
    if (!p || typeof p.name !== 'string' || typeof p.token !== 'string' || !p.token || tokens.has(p.token)) continue;
    const id = typeof p.id === 'string' && p.id && !ids.has(p.id) ? p.id : newId();
    tokens.add(p.token);
    ids.add(id);
    profiles.push({ id, name: p.name, token: p.token, invalid: p.invalid === true });
  }
  return { active: typeof data?.active === 'string' ? data.active : null, profiles };
}

function persist() {
  try {
    localStorage.setItem(STORE_KEY, JSON.stringify({ version: 1, active: S.activeId, profiles: S.profiles }));
    return true;
  } catch {
    toast(t('profile.saveFailed'));
    return false;
  }
}

const activeProfile = () => S.profiles.find((p) => p.id === S.activeId) || null;
const lostText = (p) => t('add.lost', { name: p.name });

function makeApi(profile) {
  const api = createApi({
    token: profile.token,
    onUnauthorized: () => {
      if (S.api === api) tokenLost(profile.id);
    },
    onConnection: (ok) => {
      if (S.api === api) setOnline(ok);
    },
  });
  return api;
}

function setOnline(ok) {
  $('offline').hidden = ok;
}

/** Makes a valid profile the active one and loads the state. Returns false when the browser did not save it. */
function activate(id) {
  const p = S.profiles.find((x) => x.id === id);
  if (!p || p.invalid) return false;
  if (S.activeId !== p.id) resetData();
  S.activeId = p.id;
  S.api = makeApi(p);
  const saved = persist();
  renderPerson();
  hideAdd();
  refresh();
  return saved;
}

/** Any 401: the token no longer matches config.php. */
function tokenLost(id) {
  const p = S.profiles.find((x) => x.id === id);
  if (!p) return;
  p.invalid = true;
  S.api = null;
  resetData();
  persist();
  renderPerson();
  showAdd(lostText(p));
}

/** Forgets everything loaded with the previous token. */
function resetData() {
  S.state = null;
  S.fetchedAt = 0;
  S.clockOffset = 0;
  S.wallRev = null;
  S.viewWanted = null;
  S.settingsWanted = null;
  S.pollDirty = false;
  S.notify = null;
  S.notifyBase = '';
  S.notifyChips = { done: '', wait: '' };
  stopPlayback();
  for (const url of S.blobs.values()) URL.revokeObjectURL(url);
  S.blobs.clear();
  for (const id of ERROR_IDS) $(id).textContent = '';
  showStateError('');
  setOnline(true);
  render();
}

function addProfile(name, token) {
  // the same token again, or a new token for a person whose old one stopped working
  let p = S.profiles.find((x) => x.token === token) || S.profiles.find((x) => x.invalid && x.name === name);
  if (p) {
    p.name = name;
    p.token = token;
    p.invalid = false;
  } else {
    p = { id: newId(), name, token, invalid: false };
    S.profiles.push(p);
  }
  return p;
}

