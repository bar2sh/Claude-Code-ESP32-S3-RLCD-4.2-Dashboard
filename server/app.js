// ---------- board animations (lib/anim.js) on canvas ----------

// WCAG 2.2.2: nothing moves on its own for longer than 5 s. A canvas plays as many whole cycles as fit in
// that time (at least one) and then stands on the key frame; with reduced motion it starts there. Picking
// an animation plays it once, also with reduced motion: the user asked for it.
const PLAY_MS = 5000;
const stillMotion = matchMedia('(prefers-reduced-motion: reduce)');
const shown = new Map(); // canvas -> {anim, start, cycles, frame}
const frameImages = new WeakMap(); // frame bytes -> ImageData
let animRaf = 0;

const cycleMs = (anim) => anim.ms.reduce((sum, ms) => sum + ms, 0);

function cyclesFor(anim, picked) {
  if (picked) return 1;
  if (stillMotion.matches) return 0;
  return Math.max(1, Math.floor(PLAY_MS / cycleMs(anim)));
}

/** The frame `elapsed` ms after the start; the key frame once the cycles are over. */
function frameAt(m, elapsed) {
  const total = cycleMs(m.anim);
  if (elapsed >= m.cycles * total) return m.anim.key;
  let left = elapsed % total;
  for (let i = 0; i < m.anim.ms.length; i++) {
    left -= m.anim.ms[i];
    if (left < 0) return i;
  }
  return m.anim.key;
}

const darkScheme = matchMedia('(prefers-color-scheme: dark)');
const cutouts = new Map(); // "ink hole" colours -> WeakMap(frame bytes -> ImageData)

/** A colour token from app.css as [r, g, b], or null when it is not a #RRGGBB value. */
function tokenRgb(name) {
  const m = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(getComputedStyle(document.documentElement).getPropertyValue(name).trim());
  return m ? m.slice(1).map((h) => parseInt(h, 16)) : null;
}

/**
 * The board previews are board pixels (black on white). The Dashboard's Clawd is a cut-out in the theme's
 * orange (--clawd, eyes --clawd-eye); if the tokens cannot be read it falls back to board pixels.
 */
function paintFrame(canvas, frame) {
  const ink = canvas.classList.contains('clawd-big') ? tokenRgb('--clawd') : null;
  const hole = ink ? tokenRgb('--clawd-eye') : null;
  let cache = frameImages;
  if (ink && hole) {
    const key = `${ink} ${hole}`;
    if (!cutouts.has(key)) cutouts.set(key, new WeakMap());
    cache = cutouts.get(key);
  }
  let img = cache.get(frame);
  if (!img) {
    img = new ImageData(cache === frameImages ? frameToRgba(frame) : frameToCutout(frame, ink, hole), ANIM_SIZE, ANIM_SIZE);
    cache.set(frame, img);
  }
  const ctx = canvas.getContext('2d');
  ctx.clearRect(0, 0, ANIM_SIZE, ANIM_SIZE);
  ctx.putImageData(img, 0, 0);
}

/** The theme changed: the Dashboard's Clawd takes the other orange. */
function repaintClawd() {
  const m = shown.get($('dash-clawd'));
  if (!m) return;
  m.frame = -1;
  scheduleAnims();
}

/** Puts an animation on a canvas, null takes it off. The same one again keeps going, unless just picked. */
function setAnim(canvas, id, picked = false) {
  const anim = id ? animById(id) : null;
  if (!anim) {
    shown.delete(canvas);
    return;
  }
  const m = shown.get(canvas);
  if (m && m.anim === anim && !picked) return;
  shown.set(canvas, { anim, start: performance.now(), cycles: cyclesFor(anim, picked), frame: -1 });
  scheduleAnims();
}

/** A new 5 s window for every canvas: the Board or Dashboard tab opened, or the motion setting changed. */
function replayAnims() {
  const now = performance.now();
  for (const m of shown.values()) {
    m.start = now;
    m.cycles = cyclesFor(m.anim, false);
    m.frame = -1;
  }
  scheduleAnims();
}

const animsOnScreen = () => (S.tab === BOARD_TAB || S.tab === DASH_TAB) && !S.adding && document.visibilityState === 'visible';

/** Paints the frames that changed; asks for the next frame only while something plays on screen. */
function animTick(now) {
  animRaf = 0;
  let playing = false;
  for (const [canvas, m] of shown) {
    const elapsed = Math.max(0, now - m.start); // a frame's time can be a moment before setAnim's performance.now()
    const f = frameAt(m, elapsed);
    if (f !== m.frame) {
      m.frame = f;
      paintFrame(canvas, m.anim.frames[f]);
    }
    if (elapsed < m.cycles * cycleMs(m.anim)) playing = true;
  }
  if (playing && animsOnScreen()) animRaf = requestAnimationFrame(animTick);
}

function scheduleAnims() {
  if (!animRaf) animTick(performance.now());
}

