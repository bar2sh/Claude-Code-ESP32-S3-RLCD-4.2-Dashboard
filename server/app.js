function spin() {
  const on = S.manual && S.refreshing;
  const b = $('refresh');
  b.classList.toggle('spin', on);
  if (on) b.setAttribute('aria-busy', 'true');
  else b.removeAttribute('aria-busy');
}

/** GET state. One request at a time; a call during a request asks for one more after it. */
async function refresh(manual = false) {
  if (manual) S.manual = true;
  const api = S.api;
  if (!api) {
    S.manual = false;
    spin();
    return;
  }
  if (S.refreshing) {
    S.again = true;
    spin();
    return;
  }
  S.refreshing = true;
  spin();
  if (!S.state) render();
  try {
    const { state, serverTime } = await api.state();
    if (!state || typeof state !== 'object' || Array.isArray(state)) {
      throw new ApiError(t('state.badFormat'));
    }
    if (api === S.api) {
      S.state = state;
      S.fetchedAt = Date.now();
      S.clockOffset = serverTime === null ? 0 : serverTime - S.fetchedAt;
      showStateError('');
    }
  } catch (e) {
    if (api === S.api && !quiet(e)) showStateError(errorMessage(e));
  } finally {
    S.refreshing = false;
    if (S.again) {
      S.again = false;
      refresh();
    } else {
      S.manual = false;
    }
    spin();
    if (api === S.api) render();
  }
}

