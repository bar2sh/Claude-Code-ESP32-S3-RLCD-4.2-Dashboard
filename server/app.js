let chipSeq = 0;

/** One sound chip; `name` is its radio group, `where` tells togglePlay where to show a playback error. */
function chip({ id, label, lib }, { name = 'sound', picked = S.sound, where = 'chip' } = {}) {
  const node = $('tpl-chip').content.firstElementChild.cloneNode(true);
  const input = node.querySelector('input');
  const lab = node.querySelector('label');
  input.id = `sound-${++chipSeq}`;
  input.name = name;
  input.value = id;
  input.checked = id === picked;
  lab.htmlFor = input.id;
  lab.textContent = label;
  if (lib) {
    const play = $('tpl-play').content.firstElementChild.cloneNode(true);
    play.dataset.name = label;
    setPlayLabel(play, false);
    play.addEventListener('click', () => togglePlay(id, play, where));
    node.append(play);
  }
  return node;
}

/** The chips are rebuilt only when the library changes, so a refresh does not take the focus away. */
function renderChips() {
  const lib = library();
  const key = JSON.stringify(lib.map((s) => [s.id, s.name]));
  if (key !== S.chipsKey) {
    S.chipsKey = key;
    if (!TONES.some((x) => x.id === S.sound) && !lib.some((s) => s.id === S.sound)) S.sound = 'none';
    if (S.playing?.where === 'chip') stopPlayback();
    const frag = document.createDocumentFragment();
    for (const tone of TONES) frag.append(chip({ id: tone.id, label: tone.label }));
    for (const s of lib) frag.append(chip({ id: s.id, label: s.name, lib: true }));
    $('sound-chips').replaceChildren(frag);
  }
  renderSoundDesc();
}

/** The hint under a row of sound chips; `silent` replaces the text of Cisza. '' for a sound the library lost. */
