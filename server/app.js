const fmtTime = new Intl.DateTimeFormat(locale(), { hour: '2-digit', minute: '2-digit' });
const fmtDay = new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
const fmtYear = new Intl.DateTimeFormat(locale(), {
  day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
});

const serverNow = () => Date.now() + S.clockOffset;

/** Server time (seconds) as "14:05" today, "5 Nov, 14:05" this year, else with the year. */
function when(ts) {
  const sec = Number(ts);
  if (!(sec > 0)) return '';
  const d = new Date(sec * 1000);
  const now = new Date(serverNow());
  if (d.toDateString() === now.toDateString()) return fmtTime.format(d);
  return (d.getFullYear() === now.getFullYear() ? fmtDay : fmtYear).format(d);
}

function seconds(ms) {
  const s = Math.max(0, Number(ms) || 0) / 1000;
  return s.toLocaleString(locale(), { minimumFractionDigits: 1, maximumFractionDigits: 1 });
}

const kilobytes = (n) => `${Math.max(1, Math.round(n / 1000)).toLocaleString(locale())} kB`;

function monogram(name) {
  const first = [...String(name).trim()][0];
  return first ? first.toLocaleUpperCase('pl') : '?';
}

function newId() {
  if (globalThis.crypto && typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  return Date.now().toString(36) + Math.random().toString(36).slice(2);
}

function errorMessage(e) {
  if (e instanceof ApiError || e instanceof SoundError) return ui(e.message);
  if (e && e.name === 'NotAllowedError') return ui(t('err.playBlocked'));
  if (e && e.name === 'NotSupportedError') return ui(t('err.playUnsupported'));
  return ui(t('err.unexpected', { detail: e && e.message ? e.message : String(e) }));
}

