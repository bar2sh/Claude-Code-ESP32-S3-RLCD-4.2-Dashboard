/** The page's own texts: data-i18n sets the text, data-i18n-aria-label and data-i18n-placeholder the attributes. */
function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = ui(t(el.dataset.i18n));
  for (const el of root.querySelectorAll('[data-i18n-aria-label]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const tpl of root.querySelectorAll('template')) applyStatic(tpl.content); // querySelectorAll skips templates
}

/** <html lang>, the title, the description and the manifest follow the language of this page load. */
function applyLanguage() {
  const code = lang();
  document.documentElement.lang = code;
  document.title = t('app.name');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('app.description'));
  document.querySelector('meta[name="apple-mobile-web-app-title"]')?.setAttribute('content', t('app.name'));
  document.querySelector('link[rel="manifest"]')
    ?.setAttribute('href', code === DEFAULT_LANG ? 'manifest.webmanifest' : `manifest-${code}.webmanifest`);
  checkLang();
}

// The language pickers: People → Settings, and the first-run screen while the device has no profile
// (docs/SPEC.md, "Język"). Each has its own radio name, so the two groups never uncheck each other.
const LANG_PICKERS = [
  { box: 'lang-options', name: 'app-lang', error: 'lang-error' },
  { box: 'first-lang-options', name: 'first-lang', error: 'first-lang-error' },
];

function checkLang() {
  for (const { box, name } of LANG_PICKERS) {
    for (const r of $(box).querySelectorAll(`input[name="${name}"]`)) r.checked = r.value === lang();
  }
}

/** A new language is saved on this device and the app reloads, so one page load never mixes two languages. */
function onLang(picker, e) {
  const target = e.target;
  if (!(target instanceof HTMLInputElement) || target.name !== picker.name || target.value === lang()) return;
  if (saveLang(target.value)) {
    location.reload();
    return;
  }
  $(picker.error).textContent = ui(t('settings.saveFailed'));
  checkLang();
}

