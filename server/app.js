/**
 * The sound chips of one notification: the tones, the library, and a sound the settings name but the
 * library no longer has. Rebuilt only when those change, so picking a chip keeps the focus on it.
 */
function renderNotifySounds(kind) {
  const lib = library();
  const saved = serverNotify()?.[kind]?.sound;
  const key = JSON.stringify([lib.map((s) => [s.id, s.name]), saved]);
  if (key === S.notifyChips[kind]) return;
  S.notifyChips[kind] = key;
  const where = `notify-${kind}`;
  if (S.playing?.where === where) stopPlayback();
  const known = (id) => TONES.some((x) => x.id === id) || lib.some((s) => s.id === id);
  const gone = [...new Set([saved, S.notify[kind].sound])].filter((id) => typeof id === 'string' && !known(id));
  const opts = { name: `notify-${kind}-sound`, picked: S.notify[kind].sound, where };
  const frag = document.createDocumentFragment();
  for (const tone of TONES) frag.append(chip({ id: tone.id, label: tone.label }, opts));
  for (const s of lib) frag.append(chip({ id: s.id, label: s.name, lib: true }, opts));
  for (const id of gone) frag.append(chip({ id, label: ui(t('sound.goneChip')) }, opts));
  $(`notify-${kind}-sounds`).replaceChildren(frag);
  revealPicked($(`notify-${kind}-sounds`));
}

/** Scrolls a chip strip, never the page, so that its checked chip is in view; a hidden strip stays as it is. */
function revealPicked(strip) {
  const node = strip.querySelector('input:checked')?.closest('.choice');
  if (!node || !strip.clientWidth) return;
  const css = getComputedStyle(strip);
  const s = strip.getBoundingClientRect();
  const c = node.getBoundingClientRect();
  const left = s.left + (parseFloat(css.scrollPaddingInlineStart) || 0);
  const right = s.right - (parseFloat(css.scrollPaddingInlineEnd) || 0);
  if (c.right > right) strip.scrollLeft += c.right - right;
  else if (c.left < left) strip.scrollLeft -= left - c.left;
}

