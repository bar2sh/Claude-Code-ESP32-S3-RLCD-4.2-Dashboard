/**
 * Board settings from both panels go through one queue: a change picked while a save runs is sent after it,
 * together with every other change picked meanwhile.
 */
async function queueSettings(change) {
  S.settingsWanted = { ...S.settingsWanted, ...change };
  for (const key of Object.keys(change)) $(settingsPart(key).err).textContent = '';
  if (S.settingsBusy) return; // the running request sends the newest choice after it
  const api = S.api;
  if (!api) return;
  S.settingsBusy = true;
  let saved = null;
  let body = null;
  const done = {}; // every field saved in this run, for the toast
  try {
    while (S.settingsWanted && api === S.api) {
      body = S.settingsWanted;
      S.settingsWanted = null;
      busySettings(body, true);
      saved = (await api.setSettings(body))?.settings ?? saved;
      busySettings(body, false);
      Object.assign(done, body);
    }
  } catch (ex) {
    busySettings(body, false);
    S.settingsWanted = null;
    if (api === S.api) {
      for (const key of Object.keys(body)) $(settingsPart(key).err).textContent = errorMessage(ex);
      if (body.poll_s != null) S.pollDirty = true; // the typed seconds stay for another try
    }
  } finally {
    S.settingsBusy = false;
  }
  if (api !== S.api) return;
  if (saved && S.state) S.state.settings = saved;
  checkSettings();
  renderPoll();
  if (saved) toast(settingsToast(done));
  renderDevice();
  refresh();
}

