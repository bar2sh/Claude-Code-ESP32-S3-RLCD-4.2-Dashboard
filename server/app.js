function renderPeople() {
  const frag = document.createDocumentFragment();
  for (const p of S.profiles) {
    const li = $('tpl-person').content.firstElementChild.cloneNode(true);
    const isActive = p.id === S.activeId;
    li.querySelector('.mono').textContent = monogram(p.name);
    li.querySelector('.pname').textContent = p.name;
    li.querySelector('.pnote').textContent = p.invalid ? t('people.dead') : isActive ? t('people.active') : '';
    const pick = li.querySelector('.switch');
    if (isActive && !p.invalid) pick.setAttribute('aria-current', 'true');
    pick.addEventListener('click', () => onPickPerson(p.id));
    const remove = li.querySelector('.remove');
    remove.setAttribute('aria-label', t('people.removeName', { name: p.name }));
    remove.addEventListener('click', () => onRemovePerson(p.id));
    frag.append(li);
  }
  $('people-list').replaceChildren(frag);
}

function onPickPerson(id) {
  const p = S.profiles.find((x) => x.id === id);
  if (!p) return;
  closeDialog($('people'));
  if (p.invalid) {
    // a dead token: straight to "Add person" for this person
    if (S.activeId !== p.id) {
      resetData();
      S.activeId = p.id;
      S.api = null;
      persist();
      renderPerson();
    }
    showAdd(lostText(p));
    return;
  }
  if (p.id === S.activeId && S.api && !S.adding) return;
  activate(p.id);
}

async function onRemovePerson(id) {
  const p = S.profiles.find((x) => x.id === id);
  if (!p) return;
  const ok = await confirmDialog(t('people.removeConfirm', { name: p.name }), t('action.remove'));
  if (!ok) return;
  S.profiles = S.profiles.filter((x) => x.id !== id);
  const wasActive = S.activeId === id;
  if (wasActive) {
    S.activeId = null;
    S.api = null;
    resetData();
  }
  persist();
  renderPerson();
  if (!wasActive) {
    renderPeople();
    $('people-close').focus();
    return;
  }
  const next = S.profiles.find((x) => !x.invalid);
  if (next) {
    activate(next.id);
    renderPeople();
    $('people-close').focus();
  } else {
    closeDialog($('people'));
    showAdd('');
  }
}

// ---------- tabs ----------

function showTab(i, focus) {
  S.tab = i;
  TABS.forEach(([tab, panel], k) => {
    const b = $(tab);
    b.setAttribute('aria-selected', k === i ? 'true' : 'false');
    b.tabIndex = k === i ? 0 : -1;
    $(panel).hidden = S.adding || k !== i;
  });
  $('tabs').dataset.active = String(i);
  if (focus) $(TABS[i][0]).focus();
  if (i === WALL_TAB && !S.adding) loadWallpaper();
  if (i === DASH_TAB && !S.adding) replayAnims();
  if (i === BOARD_TAB && !S.adding) {
    replayAnims();
    for (const kind of NOTIFY_KINDS) revealPicked($(`notify-${kind}-sounds`)); // the saved sound may sit off to the right
  }
}

function selectTab(i, focus = false) {
  const changed = i !== S.tab;
  showTab(i, focus);
  if (changed) window.scrollTo(0, 0);
}

function onTabKey(e) {
  const n = TABS.length;
  let i;
  if (e.key === 'ArrowRight') i = (S.tab + 1) % n;
  else if (e.key === 'ArrowLeft') i = (S.tab + n - 1) % n;
  else if (e.key === 'Home') i = 0;
  else if (e.key === 'End') i = n - 1;
  else return;
  e.preventDefault();
  selectTab(i, true);
}

