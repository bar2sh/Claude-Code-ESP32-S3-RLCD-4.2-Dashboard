/** The frames of a BAKED entry: base64, then PackBits, then each frame XOR the one before it. */
function unpack({ ms, data }) {
  const bin = atob(data);
  const all = new Uint8Array(ms.length * BYTES);
  let at = 0;
  for (let i = 0; i < bin.length;) {
    const n = bin.charCodeAt(i++);
    if (n < 128) {
      for (let k = 0; k <= n; k++) all[at++] = bin.charCodeAt(i++);
    } else if (n > 128) {
      all.fill(bin.charCodeAt(i++), at, at + 257 - n);
      at += 257 - n;
    }
  }
  if (at !== all.length) throw new Error(`anim.js: ${at} bytes of frames, ${all.length} expected`);
  for (let i = BYTES; i < all.length; i++) all[i] ^= all[i - BYTES];
  return ms.map((_, f) => all.slice(f * BYTES, (f + 1) * BYTES));
}

const clawd = (id, name, svg) => ({ id, name, svg, ms: BAKED[id].ms, key: BAKED[id].key, frames: unpack(BAKED[id]) });

