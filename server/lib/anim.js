/**
 * The corner animation of the session list, by the most important state (docs/SPEC.md,
 * "Róg widoku Sesje Claude"): a waiting row, a working row, all rows done, an empty list.
 * null leaves the corner empty: while a row is working (as on the board, since 64d1514)
 * and when the list has more than CORNER_MAX_ROWS rows and needs the corner itself.
 */
export function cornerAnim(rows) {
  if (rows.length > CORNER_MAX_ROWS) return null;
  if (rows.some((r) => r.state === 'waiting')) return 'alert';
  if (rows.some((r) => r.state === 'working')) return null;
  return rows.length > 0 ? 'idle' : 'sleep';
}

/** How long after a session finishes the Dashboard's Clawd is happy about it, in seconds. */
export const HAPPY_S = 90;

/**
 * The big Clawd of the app's Dashboard, by the most important state (docs/SPEC.md, "Dashboard"):
 * a waiting row -> alert, a working row -> typing, a row that finished less than HAPPY_S ago -> happy,
 * other rows (all done long ago) -> idle, no rows -> sleep. `rows` have `state` and `age` in seconds;
 * `extra` is the time since the rows were fetched, so the happy moment ends on its own.
 */
export function dashboardAnim(rows, extra = 0) {
  if (rows.some((r) => r.state === 'waiting')) return 'alert';
  if (rows.some((r) => r.state === 'working')) return 'typing';
  if (rows.some((r) => r.state === 'done' && Number.isFinite(r.age) && r.age + extra < HAPPY_S)) return 'happy';
  return rows.length > 0 ? 'idle' : 'sleep';
}

/** A frame as RGBA pixels for ImageData: black on white, as the board shows it. */
export function frameToRgba(frame) {
  const rgba = new Uint8ClampedArray(SIZE * SIZE * 4);
  for (let i = 0; i < SIZE * SIZE; i++) {
    const v = frame[i >> 3] & (0x80 >> (i & 7)) ? 0 : 255;
    rgba[i * 4] = v;
    rgba[i * 4 + 1] = v;
    rgba[i * 4 + 2] = v;
    rgba[i * 4 + 3] = 255;
  }
  return rgba;
}

/**
 * A frame as a cut-out in colour, for the Dashboard's Clawd: set bits in `ink`, white that the ink
 * encloses (the eyes) in `hole`, and white that reaches the frame's edge transparent. Colours are [r, g, b].
 */
export function frameToCutout(frame, ink, hole) {
  const n = SIZE * SIZE;
  const set = (i) => (frame[i >> 3] & (0x80 >> (i & 7))) !== 0;
  const outside = new Uint8Array(n);
  const todo = [];
  for (let i = 0; i < n; i++) {
    const x = i % SIZE;
    const y = (i - x) / SIZE;
    if ((x === 0 || y === 0 || x === SIZE - 1 || y === SIZE - 1) && !set(i)) {
      outside[i] = 1;
      todo.push(i);
    }
  }
  while (todo.length) {
    const i = todo.pop();
    const x = i % SIZE;
    for (const j of [x > 0 ? i - 1 : -1, x < SIZE - 1 ? i + 1 : -1, i - SIZE, i + SIZE]) {
      if (j >= 0 && j < n && !outside[j] && !set(j)) {
        outside[j] = 1;
        todo.push(j);
      }
    }
  }
  const rgba = new Uint8ClampedArray(n * 4);
  for (let i = 0; i < n; i++) {
    if (outside[i]) continue; // transparent black
    const c = set(i) ? ink : hole;
    rgba.set([c[0], c[1], c[2], 255], i * 4);
  }
  return rgba;
}
