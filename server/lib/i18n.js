let current = DEFAULT_LANG;

export const isLang = (code) => LANGS.includes(code);
/** The language of this page load. */
export const lang = () => current;
export const locale = () => LOCALES[current];

/** Sets the language of this page load; anything but a known code gives the default. */
export function setLang(code) {
  current = isLang(code) ? code : DEFAULT_LANG;
  return current;
}

// localStorage itself can throw (blocked site data), so it is read inside try, never as a default value.
const storeOf = (storage) => (storage === undefined ? globalThis.localStorage : storage);

/** The language saved on this device, or the default when there is none or storage is blocked. */
export function loadLang(storage) {
  try {
    const code = storeOf(storage)?.getItem(LANG_KEY);
    return isLang(code) ? code : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

/** Saves the language on this device; false when the code is unknown or the browser did not keep it. */
export function saveLang(code, storage) {
  if (!isLang(code)) return false;
  try {
    const store = storeOf(storage);
    store.setItem(LANG_KEY, code);
    return store.getItem(LANG_KEY) === code;
  } catch {
    return false;
  }
}

/** The text for key in the current language, then in English, then the key itself; {name} from params. */
export function t(key, params) {
  const text = DICT[current][key] ?? DICT[DEFAULT_LANG][key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (all, name) => (Object.hasOwn(params, name) ? String(params[name]) : all));
}

/** A counted text: key.one, key.few, key.many or key.other by the plural rules of the language; {n} is n. */
export function tn(key, n, params = {}) {
  const form = new Intl.PluralRules(locale()).select(n);
  return t(`${key}.${form}`, { ...params, n });
}
