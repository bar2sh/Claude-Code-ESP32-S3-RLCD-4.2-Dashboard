#!/usr/bin/env node
// Writes the notification animations of server/lib/anim.js to firmware/main/anim_frames.c and
// anim_frames.h, so the board draws the same frames as the app (docs/SPEC.md, "Animacje").
// Needs only Node, nothing to install.
//
//     node tools/anim2c.mjs           writes both files
//     node tools/anim2c.mjs --check   exits with 1 when a file differs from anim.js (the tests run it)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ANIMS, BYTES, ROW, SIZE } from '../server/lib/anim.js';

const OUT = {
  'anim_frames.h': fileURLToPath(new URL('../firmware/main/anim_frames.h', import.meta.url)),
  'anim_frames.c': fileURLToPath(new URL('../firmware/main/anim_frames.c', import.meta.url)),
};
const HEAD = '// Generated by tools/anim2c.mjs from server/lib/anim.js. Do not edit: change anim.js, then run\n'
  + '// node tools/anim2c.mjs.\n';

function validate() {
  const fail = (text) => {
    throw new Error(`server/lib/anim.js: ${text}`);
  };
  for (const a of ANIMS) {
    if (!/^[a-z]+$/.test(a.id)) fail(`id "${a.id}" must be lowercase letters`);
    if (a.frames.length < 1 || a.frames.length > 255) fail(`${a.id} must have 1-255 frames`);
    if (a.ms.length !== a.frames.length) fail(`${a.id} must have one ms value per frame`);
    if (!a.ms.every((ms) => Number.isInteger(ms) && ms > 0 && ms <= 65535)) fail(`${a.id} ms must be 1-65535`);
    if (!a.frames.every((f) => f instanceof Uint8Array && f.length === BYTES)) fail(`${a.id} frames must be ${BYTES} bytes`);
  }
}

function header() {
  const ids = ANIMS.map((a) => `ANIM_${a.id.toUpperCase()}`).join(', ');
  return `${HEAD}#pragma once
#include <stdint.h>

#define ANIM_SIZE ${SIZE}
#define ANIM_BYTES ${BYTES} // rows from the top, ${ROW} bytes per row, the most significant bit is the leftmost pixel, 1 = black

typedef enum { ${ids}, ANIM_COUNT } anim_id_t;

typedef struct {
    const char *id;     // as in the notify settings from the server
    uint8_t count;      // frames
    const uint16_t *ms; // how long each frame shows; the last one includes the pause
    const uint8_t (*frames)[ANIM_BYTES];
} anim_t;

extern const anim_t ANIMS[ANIM_COUNT];

int anim_find(const char *id); // the anim_id_t of an id, -1 when unknown
`;
}

function source() {
  const hex = (frame) => {
    const lines = [];
    for (let i = 0; i < frame.length; i += 16) {
      lines.push(`        ${Array.from(frame.subarray(i, i + 16), (b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ')},`);
    }
    return lines.join('\n');
  };
  const parts = [`${HEAD}#include "anim_frames.h"\n#include <stddef.h>\n#include <string.h>\n`];
  for (const a of ANIMS) {
    const n = a.id.toUpperCase();
    const frames = a.frames.map((f, i) => `    { // frame ${i}\n${hex(f)}\n    },`).join('\n');
    parts.push(`// ${a.id}: ${a.name}
static const uint16_t MS_${n}[${a.ms.length}] = {${a.ms.join(', ')}};
static const uint8_t FRAMES_${n}[${a.frames.length}][ANIM_BYTES] = {
${frames}
};
`);
  }
  const rows = ANIMS.map((a) => `    {"${a.id}", ${a.frames.length}, MS_${a.id.toUpperCase()}, FRAMES_${a.id.toUpperCase()}},`);
  parts.push(`const anim_t ANIMS[ANIM_COUNT] = {
${rows.join('\n')}
};

int anim_find(const char *id)
{
    for (int i = 0; id != NULL && i < ANIM_COUNT; i++) {
        if (strcmp(ANIMS[i].id, id) == 0) return i;
    }
    return -1;
}
`);
  return parts.join('\n');
}

validate();
const files = { 'anim_frames.h': header(), 'anim_frames.c': source() };
if (process.argv.includes('--check')) {
  const stale = Object.keys(files).filter((name) => !existsSync(OUT[name]) || readFileSync(OUT[name], 'utf8') !== files[name]);
  if (stale.length) {
    console.error(`firmware/main/${stale.join(', firmware/main/')} differs from server/lib/anim.js: run node tools/anim2c.mjs`);
    process.exit(1);
  }
  console.log('firmware/main/anim_frames.c and anim_frames.h match server/lib/anim.js');
} else {
  for (const [name, text] of Object.entries(files)) writeFileSync(OUT[name], text);
  console.log(`wrote firmware/main/anim_frames.c and anim_frames.h: ${ANIMS.length} animations, `
    + `${ANIMS.reduce((n, a) => n + a.frames.length, 0)} frames`);
}
